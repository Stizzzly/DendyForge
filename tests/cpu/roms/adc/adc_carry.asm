;=========================================================
; ROM TEMPLATE
;=========================================================

.segment "HEADER"

.byte 'N','E','S',$1A
.byte 2                 ; 32KB PRG ROM
.byte 1                 ; 8KB CHR ROM
.byte $00               ; Mapper 0
.byte $00
.byte $00,$00,$00,$00,$00,$00,$00,$00


;=========================================================
; RESET
;=========================================================

.segment "STARTUP"

Reset:
    SEI
    CLD
    LDX #$FF
    TXS

    JMP Main


;=========================================================
; TEST CODE
;=========================================================

.segment "CODE"

Main:

    ; ----------------------------------------------------
    ; Test code
    ; ----------------------------------------------------

    CLC

    LDA #$F0
    ADC #$20

Forever:
    JMP Forever


;=========================================================
; INTERRUPTS
;=========================================================

Dummy_Int:
    RTI


;=========================================================
; VECTORS
;=========================================================

.segment "VECTORS"

.word Dummy_Int
.word Reset
.word Dummy_Int


;=========================================================
; CHR
;=========================================================

.segment "CHARS"

.res 8192
